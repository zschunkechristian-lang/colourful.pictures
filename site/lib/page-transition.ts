// Seamless page transition between a project tile (home / project grid) and that project's hero.
//
// The old page is cross-faded away with a cross-document View Transition (Chrome, Edge, Safari 18.2+;
// other browsers simply navigate as usual). The clip itself is not part of that fade: the new page
// starts its real hero video exactly on top of the clicked tile (same box, same crop, same playback
// position), then lib/fly.ts grows that box into the header while the video keeps playing, so the
// crop changes continuously. Going back is a plain cross-fade.
//
// Both pieces below are injected into every page's <head> by renderer/+onRenderHtml.tsx, so they also
// work on the pages that are still generated by Webstudio.

export const pageTransitionCss = `
@view-transition { navigation: auto; }
:root[data-vt-fly]::view-transition-old(root) { animation: vt-out 0.3s ease both; }
:root[data-vt-fly]::view-transition-new(root) { animation: vt-in 0.3s ease both; }
@keyframes vt-out { to { opacity: 0; } }
@keyframes vt-in { from { opacity: 0; } }
/* the hero clip waits on top of the clicked tile until lib/fly.ts moves it */
:root[data-vt-fly] .hero__media > .media {
  position: fixed;
  z-index: 40;
  left: var(--vt-x);
  top: var(--vt-y);
  width: var(--vt-w);
  height: var(--vt-h);
}
@media (prefers-reduced-motion: reduce) {
  ::view-transition-group(*), ::view-transition-old(*), ::view-transition-new(*) { animation: none !important; }
}
`;

// Plain ES5 on purpose: it runs inline, before any bundle.
export const pageTransitionScript = `
(function () {
  var path = function (u) { return new URL(u, location.href).pathname.replace(/\\/$/, "") || "/"; };
  // the clip inside the tile that links to \`p\`
  var tileFor = function (p) {
    var as = document.querySelectorAll("a[href]");
    for (var i = 0; i < as.length; i++) {
      if (path(as[i].href) === p) { var m = as[i].querySelector("video, img"); if (m) return m; }
    }
    return null;
  };

  // leaving a page: remember where the clicked tile's clip is, how big it is and how far it has played
  addEventListener("pageswap", function (e) {
    try {
      if (!e.viewTransition || !e.activation || !e.activation.entry) return;
      var to = path(e.activation.entry.url);
      var el = tileFor(to);
      if (!el) return;
      e.viewTransition.ready.catch(function () {});
      var r = el.getBoundingClientRect();
      sessionStorage.setItem("vt-fly", JSON.stringify({
        p: to, x: r.left, y: r.top, w: r.width, h: r.height,
        t: el.tagName === "VIDEO" ? el.currentTime : 0, at: Date.now()
      }));
    } catch (err) {}
  });

  // arriving: before the first paint, park the hero clip on top of the tile it came from
  addEventListener("pagereveal", function (e) {
    try {
      var raw = sessionStorage.getItem("vt-fly");
      sessionStorage.removeItem("vt-fly");
      if (!e.viewTransition || !raw) return;
      var f = JSON.parse(raw);
      if (f.p !== path(location.href) || Date.now() - f.at > 8000) return;
      e.viewTransition.ready.catch(function () {});
      var root = document.documentElement;
      root.style.setProperty("--vt-x", f.x + "px");
      root.style.setProperty("--vt-y", f.y + "px");
      root.style.setProperty("--vt-w", f.w + "px");
      root.style.setProperty("--vt-h", f.h + "px");
      root.setAttribute("data-vt-fly", "");
      window.__vtFly = f;
      // lib/motion.ts waits for this before it plays the header copy; lib/fly.ts resolves it
      window.__vtDone = new Promise(function (resolve) { window.__vtResolve = resolve; setTimeout(resolve, 5000); });
      // failsafe: never leave the clip parked if the script that moves it did not run
      setTimeout(function () { root.removeAttribute("data-vt-fly"); }, 8000);
    } catch (err) {}
  });
})();
`;
